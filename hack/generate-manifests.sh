#!/usr/bin/env bash
# Fresh generation removes schemas whose Go API has been renamed or deleted.
set -euo pipefail
cd "$(dirname "$0")/.."
mkdir -p .cache chart/templates/crds
stage=$(mktemp -d "$PWD/.cache/generated.XXXXXX")
trap 'rm -rf "$stage"' EXIT
"$CONTROLLER_GEN" rbac:roleName=manager-role crd:generateEmbeddedObjectMeta=true \
  paths="./..." output:crd:artifacts:config="$stage/crds" \
  output:rbac:artifacts:config="$stage/rbac"
test -f "$stage/rbac/role.yaml"
crds=("$stage/crds/"*.yaml)
test -f "${crds[0]}"
# Add release metadata while keeping generated schemas and RBAC rules intact.
mkdir -p "$stage/templates/crds"
for manifest in "${crds[@]}" "$stage/rbac/role.yaml"; do
  if [[ "$manifest" == "$stage/rbac/role.yaml" ]]; then
    target="$stage/templates/roles.yaml"
  else
    target="$stage/templates/crds/$(basename "$manifest")"
  fi
  awk '
    BEGIN { print "# Generated by make generate. DO NOT EDIT." }
    /^kind: / { kind = $2 }
    $0 == "metadata:" {
      print
      print "  labels:"
      print "    app.kubernetes.io/name: arally-operator"
      print "    app.kubernetes.io/component: manager"
      print "    {{- include \"arally-operator.labels\" . | nindent 4 }}"
      next
    }
    $0 == "  annotations:" && kind == "CustomResourceDefinition" {
      print
      print "    helm.sh/resource-policy: keep"
      print "    meta.helm.sh/release-name: {{ .Release.Name | quote }}"
      print "    meta.helm.sh/release-namespace: {{ .Release.Namespace | quote }}"
      next
    }
    $0 == "  name: manager-role" && kind == "ClusterRole" {
      print "  name: {{ .Release.Name }}-{{ .Release.Namespace }}"
      next
    }
    $0 == "  name: manager-role" && kind == "Role" {
      print "  name: {{ .Release.Name }}-leader-election"
      next
    }
    $0 == "  namespace: system" && kind == "Role" {
      print "  namespace: {{ .Release.Namespace }}"
      next
    }
    { print }
  ' "$manifest" > "$target"
done
# Only generated files live in these locations; authored templates live elsewhere.
rm -f chart/templates/crds/*.yaml
cp "$stage/templates/crds/"*.yaml chart/templates/crds/
cp "$stage/templates/roles.yaml" chart/templates/roles.yaml
